-- Public Web tutor directory data. Column names stay aligned with the legacy
-- MySQL tables so a separate, audited import can preserve existing records.
CREATE TABLE t_tutor_info (
    tutor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_no VARCHAR(64),
    province VARCHAR(128),
    city VARCHAR(128),
    district VARCHAR(128),
    address TEXT,
    longitude NUMERIC(11,8),
    latitude NUMERIC(11,8),
    native_place VARCHAR(255),
    tutor_name VARCHAR(128),
    gender VARCHAR(16),
    age INTEGER,
    phone VARCHAR(64),
    avatar_images TEXT,
    teacher_type VARCHAR(32),
    crime_record_cert TEXT,
    id_card VARCHAR(128),
    openid VARCHAR(255),
    like_count INTEGER NOT NULL DEFAULT 0,
    grade_id BIGINT,
    university VARCHAR(255),
    major VARCHAR(255),
    subject_ids TEXT,
    subject_names TEXT,
    tutorable_grade_ids TEXT,
    tutorable_grade_names TEXT,
    student_require TEXT,
    teaching_mode VARCHAR(64),
    available_time TEXT,
    expected_salary NUMERIC(12,2),
    trial_time TEXT,
    middle_score NUMERIC(8,2),
    high_score NUMERIC(8,2),
    constellation VARCHAR(32),
    service_count INTEGER NOT NULL DEFAULT 0,
    avg_score NUMERIC(5,2),
    points INTEGER NOT NULL DEFAULT 0,
    lab_hours INTEGER,
    diy_hours INTEGER,
    accept_minimalist CHAR(1),
    other_info TEXT,
    personal_profile TEXT,
    status CHAR(1) NOT NULL DEFAULT '0',
    audit_status CHAR(1) NOT NULL DEFAULT '0',
    audit_time TIMESTAMP WITHOUT TIME ZONE,
    audit_remark TEXT,
    del_flag CHAR(1) NOT NULL DEFAULT '0',
    deposit_amount NUMERIC(12,2),
    deposit_transaction_id VARCHAR(255),
    deposit_status CHAR(1),
    create_by VARCHAR(128),
    create_time TIMESTAMP WITHOUT TIME ZONE,
    update_by VARCHAR(128),
    update_time TIMESTAMP WITHOUT TIME ZONE,
    remark TEXT
);

CREATE INDEX idx_tutor_public_state ON t_tutor_info (status, audit_status, del_flag);
CREATE INDEX idx_tutor_public_created ON t_tutor_info (create_time DESC, tutor_id DESC);

CREATE TABLE t_tutor_qualification (
    qualification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id BIGINT NOT NULL,
    teacher_certificate TEXT,
    teaching_experience TEXT,
    character_intro TEXT,
    honor_images TEXT,
    other_advantage TEXT,
    resume_url TEXT,
    create_time TIMESTAMP WITHOUT TIME ZONE,
    update_time TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX idx_tutor_qualification_latest ON t_tutor_qualification (tutor_id, qualification_id DESC);
