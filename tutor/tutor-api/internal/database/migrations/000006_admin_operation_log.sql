-- Preserve audit metadata while deliberately excluding request/response/error payloads during legacy import.
CREATE TABLE sys_oper_log (
    oper_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT,
    business_type INTEGER,
    method TEXT,
    request_method TEXT,
    operator_type INTEGER,
    oper_name TEXT,
    dept_name TEXT,
    oper_url TEXT,
    oper_ip TEXT,
    oper_location TEXT,
    oper_param TEXT,
    action_meta TEXT NOT NULL DEFAULT '{}',
    json_result TEXT,
    status INTEGER,
    error_msg TEXT,
    oper_time TIMESTAMP WITHOUT TIME ZONE,
    cost_time BIGINT
);

CREATE INDEX idx_sys_oper_log_time_id
    ON sys_oper_log (oper_time DESC NULLS LAST, oper_id DESC);