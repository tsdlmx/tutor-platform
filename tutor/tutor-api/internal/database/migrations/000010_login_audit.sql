-- Authentication audit trail. Kept separate from sys_oper_log because it records
-- security events rather than business changes, and because it must be retained
-- for at least six months without mixing in request or response payloads.
-- The identifier is masked before insert; the raw account address is never stored.
CREATE TABLE sys_login_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_type VARCHAR(16) NOT NULL,
    identifier VARCHAR(255) NOT NULL,
    client_ip VARCHAR(64),
    user_agent VARCHAR(255),
    result VARCHAR(16) NOT NULL,
    reason VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_sys_login_audit_time_id
    ON sys_login_audit (created_at DESC, audit_id DESC);

CREATE INDEX idx_sys_login_audit_identifier_time
    ON sys_login_audit (identifier, created_at DESC);

CREATE INDEX idx_sys_login_audit_ip_time
    ON sys_login_audit (client_ip, created_at DESC);
