-- Evidence that a customer was told about, and agreed to, the privacy policy and
-- user agreement in force when the account was created. The identifier of the
-- policy version is stored instead of the policy text so the record stays stable
-- while the published document is updated.
CREATE TABLE t_customer_consent (
    consent_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    consent_type VARCHAR(32) NOT NULL,
    policy_version VARCHAR(32) NOT NULL,
    client_ip VARCHAR(64),
    consented_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_customer_consent_account ON t_customer_consent (account_id, consented_at DESC);
