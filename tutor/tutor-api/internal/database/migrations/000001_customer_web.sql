-- Initial schema for the Web customer features.
-- Keep legacy names/columns where practical to simplify an audited data import.
-- This migration intentionally does not create admin/system tables; those are
-- modeled and migrated in later, reviewed slices.

CREATE TABLE t_customer_account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(128) NOT NULL,
    password VARCHAR(100) NOT NULL,
    nickname VARCHAR(64),
    role VARCHAR(16),
    status CHAR(1) NOT NULL DEFAULT '0',
    last_login_time TIMESTAMP WITHOUT TIME ZONE,
    create_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_customer_email_lower ON t_customer_account (lower(email));

CREATE TABLE t_customer_session (
    session_key VARCHAR(32) PRIMARY KEY,
    account_id BIGINT NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITHOUT TIME ZONE,
    create_time TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_customer_session_account ON t_customer_session (account_id);
CREATE INDEX idx_customer_session_expiry ON t_customer_session (expires_at);

CREATE TABLE t_teacher_profile (
    account_id BIGINT PRIMARY KEY,
    real_name VARCHAR(64),
    gender CHAR(1) NOT NULL DEFAULT '0',
    age INTEGER,
    city VARCHAR(64),
    education VARCHAR(32),
    school VARCHAR(128),
    major VARCHAR(128),
    subjects VARCHAR(255),
    grades VARCHAR(255),
    hourly_rate NUMERIC(10,2),
    experience_years INTEGER,
    available_time VARCHAR(255),
    intro TEXT,
    certificates TEXT,
    contact VARCHAR(128),
    create_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE t_student_demand (
    demand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    title VARCHAR(128) NOT NULL,
    subjects VARCHAR(255) NOT NULL,
    grade VARCHAR(32),
    budget_min NUMERIC(10,2),
    budget_max NUMERIC(10,2),
    budget_unit VARCHAR(16) NOT NULL DEFAULT 'hour',
    class_mode VARCHAR(16) NOT NULL DEFAULT 'both',
    city VARCHAR(64),
    description TEXT,
    status CHAR(1) NOT NULL DEFAULT '0',
    del_flag CHAR(1) NOT NULL DEFAULT '0',
    create_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_demand_student ON t_student_demand (student_id);
CREATE INDEX idx_demand_status ON t_student_demand (status);
CREATE INDEX idx_demand_create ON t_student_demand (create_time DESC);

CREATE TABLE t_demand_apply (
    apply_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    message VARCHAR(500),
    status CHAR(1) NOT NULL DEFAULT '0',
    create_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_apply_demand_teacher UNIQUE (demand_id, teacher_id)
);

CREATE INDEX idx_apply_demand ON t_demand_apply (demand_id);
CREATE INDEX idx_apply_teacher ON t_demand_apply (teacher_id);

CREATE TABLE t_user_post (
    post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    images VARCHAR(1000),
    audit_status CHAR(1) NOT NULL DEFAULT '0',
    audit_remark VARCHAR(255),
    audit_time TIMESTAMP WITHOUT TIME ZONE,
    del_flag CHAR(1) NOT NULL DEFAULT '0',
    create_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_post_account ON t_user_post (account_id);
CREATE INDEX idx_post_create ON t_user_post (create_time DESC);
CREATE INDEX idx_post_audit ON t_user_post (audit_status);
